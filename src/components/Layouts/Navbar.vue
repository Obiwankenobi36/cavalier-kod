export default {
  name: "Navbar",
  data() {
    return {
      isSticky: false,
      show: false,
      button_show_state: false,
    };
  },
  mounted() {
    const that = this;
    window.addEventListener("scroll", () => {
      let scrollPos = window.scrollY;
      if (scrollPos >= 100) {
        that.isSticky = true;
      } else {
        that.isSticky = false;
      }
    });
  },
  methods: {
    isPageWithCover() {
      return (
        this.$route.path === "/novosti" || this.$route.path === "/o-pasmini"
      );
    },
  },
};
